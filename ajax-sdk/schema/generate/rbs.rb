# frozen_string_literal: true

require_relative 'model'

module Schema
  module Generate
    # Writes the RBS of the generated values, with every type named from +::+ as in {Ruby}.
    module Rbs
      HEADER = '# Generated by schema/generate.rb from lib/ajax/sdk/cloud/schemas/; do not edit.'
      CLOUD = '::Ajax::Sdk::Cloud'
      SCALARS = { double: '::Float', float: '::Float', bool: 'bool', string: '::String', bytes: '::String' }.freeze

      module_function

      # @return [String] the RBS of the types +proto+ declares
      def file(model, proto)
        types = model.top_level(proto)
        body = types.map { type(model, it) }.reduce { |all, lines| [*all, '', *lines] }
        [HEADER, '', "module #{types.first.constant.rpartition('::').first}", *indent(body), 'end', ''].join("\n")
      end

      def type(model, type) = type.is_a?(Message) ? message(model, type) : enum(type)

      def indent(lines) = lines.map { it.empty? ? it : "  #{it}" }

      def short(type) = type.constant.split('::').last

      def message(model, message)
        members = message.fields.map { [it.name, type_of(model, it)] } << [:raw, '::Hash[::Symbol, untyped]']
        ["class #{short(message)} < ::Data", *indent(members(message, members)),
         *indent(model.nested(message.full_name).flat_map { ['', *type(model, it)] }), 'end']
      end

      def members(message, members)
        keywords = members.map { |name, type| "?#{name}: #{type}" }.join(', ')
        [*("include #{CLOUD}::Outcome" if message.outcome), 'ONEOFS: ::Hash[::Symbol, ::Array[::Symbol]]',
         *members.map { |name, type| "attr_reader #{name}: #{type}" },
         "def self.new: (#{keywords}) -> instance", 'def self.from: (::Hash[::Symbol, untyped]) -> instance',
         'def to_message: () -> ::Hash[::Symbol, untyped]',
         *message.oneofs.map { "def #{it.reader}: () -> (#{it.choices.map(&:inspect).join(' | ')})?" },
         *("def problem: () -> #{members.to_h.fetch(message.outcome.to_sym)}" if message.outcome)]
      end

      def type_of(model, field)
        return "::Hash[#{base(model, field.map.first)}, #{base(model, field.map.last)}]" if field.map
        return "::Array[#{base(model, field)}]" if field.list?
        return base(model, field) unless field.nilable?

        field.kind == :enum ? "(#{base(model, field)})?" : "#{base(model, field)}?"
      end

      def base(model, field)
        case field.kind
        when :enum then "::#{model.constant(field.type)}::value | ::Integer"
        when :message then "::#{model.constant(field.type)}"
        when :timestamp then '::Time'
        when :duration then '::Float'
        when :wrapper then SCALARS.fetch(Shapes::WRAPPERS.fetch(field.type), '::Integer')
        else SCALARS.fetch(field.type, '::Integer')
        end
      end

      def enum(enum)
        symbols = enum.values.map { it.last.inspect }.join(' | ')
        ["module #{short(enum)}", "  extend #{CLOUD}::Enum", '', "  type value = #{symbols}", '',
         '  VALUES: ::Hash[::Symbol, value]', 'end']
      end
    end
  end
end
