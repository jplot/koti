# frozen_string_literal: true

require_relative 'model'

module Schema
  module Generate
    # Writes families.rb and families.rbs: a module per family, with an autoload for each object outside another,
    # and the file each one goes to.
    module Index
      HEADER = "# Generated by schema/generate.rb from lib/miele/sdk/objects/objects.json.gz; do not edit.\n"
      OUTER = %w[Miele Sdk Objects].freeze

      module_function

      # @return [Array<Dop2Class, Dop1Class, Enum>] the objects outside another, by family then constant
      def top_level(model)
        items = [*model.dop2, *model.enums, *model.dop1.reject { nested?(it) }].sort_by(&:constant)
        Naming.distinct!('files', items.map { path(it) })
        items
      end

      # A Dop1 section sits in the file of its object.
      def nested?(item) = item.constant.count(':') > 2

      # @return [Array<Dop1Class>] the sections declared in +klass+
      def children(model, klass) = model.dop1.select { it.constant.rpartition('::').first == klass.constant }

      # @return [String] +oven/global_ps_select+: macOS folds case, so two paths must differ in more than case
      def path(item) = "#{item.family}/#{Naming.snake(item.constant.split('::').last)}"

      # @return [String] families.rb
      def ruby(model)
        families = top_level(model).group_by(&:family).flat_map do |family, items|
          autoloads = items.map { "  autoload :#{short(it)}, \"\#{__dir__}/#{path(it)}.rb\"" }
          ['', "# The objects of the app's +#{family}+ module.", "module #{Naming.constant(family)}", *autoloads, 'end']
        end
        ["# frozen_string_literal: true\n", HEADER, *wrap(families.drop(1)), ''].join("\n")
      end

      # @return [String] families.rbs
      def rbs(model)
        families = top_level(model).map(&:family).uniq.flat_map { ['', "module #{Naming.constant(it)}", 'end'] }
        [HEADER, *wrap(families.drop(1)), ''].join("\n")
      end

      def short(item) = item.constant.split('::').last

      def wrap(lines) = OUTER.reverse.reduce(lines) { |inner, name| ["module #{name}", *indent(inner), 'end'] }

      def indent(lines) = lines.map { it.empty? ? it : "  #{it}" }
    end
  end
end
